"""Download the portable engine and CC0 materials; no system installation."""
from pathlib import Path
import concurrent.futures
import hashlib
import json
import urllib.request
import zipfile

ROOT = Path(__file__).resolve().parents[1]
ENGINE = '4.7.2-stable'

def fetch(url, path):
    if not path.exists():
        req = urllib.request.Request(url, headers={'User-Agent': 'Mohashunnyo-Prototype/1.0'})
        with urllib.request.urlopen(req, timeout=180) as response:
            path.write_bytes(response.read())
    return path

def engine():
    dest = ROOT / 'tools' / 'godot'
    dest.mkdir(exist_ok=True)
    archive = fetch(f'https://github.com/godotengine/godot/releases/download/{ENGINE}/Godot_v{ENGINE}_win64.exe.zip', dest / 'engine.zip')
    if not (dest / f'Godot_v{ENGINE}_win64.exe').exists():
        with zipfile.ZipFile(archive) as z:
            z.extractall(dest)
    fetch(f'https://raw.githubusercontent.com/godotengine/godot/{ENGINE}/LICENSE.txt', dest / 'LICENSE.txt')
    fetch(f'https://raw.githubusercontent.com/godotengine/godot/{ENGINE}/COPYRIGHT.txt', dest / 'COPYRIGHT.txt')
    print('Portable Godot ready', flush=True)

def material(name):
    dest = ROOT / 'game' / 'assets' / name
    dest.mkdir(exist_ok=True)
    url = f'https://ambientcg.com/get?file={name}_1K-JPG.zip'
    archive = fetch(url, dest / 'source.zip')
    with zipfile.ZipFile(archive) as z:
        for entry in z.infolist():
            if entry.filename.endswith(('_Color.jpg', '_NormalGL.jpg', '_Roughness.jpg', '_Metalness.jpg')):
                (dest / Path(entry.filename).name).write_bytes(z.read(entry))
    metadata = {'provider': 'ambientCG', 'asset': name, 'source': f'https://ambientcg.com/view?id={name}', 'download': url, 'license': 'CC0-1.0', 'resolution': '1K', 'sha256': hashlib.sha256(archive.read_bytes()).hexdigest()}
    (dest / 'provenance.json').write_text(json.dumps(metadata, indent=2))
    print(f'{name} ready', flush=True)

def characters():
    dest = ROOT / 'game' / 'assets' / 'characters'
    dest.mkdir(exist_ok=True)
    male_url = 'https://raw.githubusercontent.com/MMWilliams/char-kit/master/characters/mh_1148.glb'
    female_url = 'https://raw.githubusercontent.com/MMWilliams/char-kit/master/characters/mh_1111.glb'
    readme_url = 'https://raw.githubusercontent.com/MMWilliams/char-kit/master/README.md'
    male = fetch(male_url, dest / 'mh_male.glb')
    female = fetch(female_url, dest / 'mh_female.glb')
    fetch(readme_url, dest / 'CHAR_KIT_README.md')
    metadata = {
        'asset': 'MakeHuman mh_1148 and mh_1111',
        'creator': 'MakeHuman bodies generated by MMWilliams/char-kit',
        'upstream': 'https://github.com/MMWilliams/char-kit',
        'downloads': [male_url, female_url],
        'bodyLicense': 'CC0-1.0 (per upstream README)',
        'maleSha256': hashlib.sha256(male.read_bytes()).hexdigest(),
        'femaleSha256': hashlib.sha256(female.read_bytes()).hexdigest(),
        'adaptation': 'Two embedded-texture bodies, shared per-variant resources, idle/walk/run clips and lightweight role accessories'
    }
    (dest / 'provenance.json').write_text(json.dumps(metadata, indent=2))
    print('Textured rigged character ready', flush=True)

if __name__ == '__main__':
    with concurrent.futures.ThreadPoolExecutor(max_workers=3) as pool:
        jobs = [pool.submit(engine), pool.submit(material, 'MetalPlates006'), pool.submit(material, 'Concrete034'), pool.submit(characters)]
        for job in jobs:
            job.result()
